/* Diagnostic PCM only. The hardware backend is the unmodified pinned SDK. */
#include "sound_diag.h"
#include "sound_sine_table.h"
#include <string.h>
#include <stdio.h>
static const unsigned frequencies[XF_SOUND_CASES][2]={{440,440},{880,880},{1000,1000},{0,0},{440,0},{0,440},{440,880}};
static const uint32_t expected_hash[XF_SOUND_CASES]={0x2616af45U,0x07fd88c5U,0x8fb36a85U,0xf5caf5c5U,0x60662be5U,0x46adbee5U,0x0a5301e5U};
static void error(xf_sound_diag *d,const char *s){d->state=XF_TONE_ERROR;snprintf(d->message,sizeof(d->message),"%s",s);}
const char *xf_sound_diag_name(unsigned mode) {
    static const char *names[XF_SOUND_CASES]={"440 Hz sine / both","880 Hz sine / both","1000 Hz sine / both","Digital silence","440 Hz LEFT only","440 Hz RIGHT only","440 LEFT / 880 RIGHT"};
    return mode<XF_SOUND_CASES?names[mode]:"Invalid test";
}
void xf_sound_diag_init(xf_sound_diag *d,const xf_audio_backend *b) {
    memset(d,0,sizeof(*d));d->backend=*b;d->seconds=1;
    snprintf(d->message,sizeof(d->message),"Ready: verify clean 440 Hz first. No automatic next stage.");
}
int xf_sound_diag_active(const xf_sound_diag *d){return d->state==XF_TONE_PLAYING || d->state==XF_TONE_DRAINING;}
int xf_sound_diag_select(xf_sound_diag *d,unsigned mode,unsigned seconds) {
    if(xf_sound_diag_active(d) || mode>=XF_SOUND_CASES || (seconds!=1 && seconds!=60))return 0;
    d->mode=mode;d->seconds=seconds;d->verified=0;return 1;
}
int xf_sound_diag_prepare(xf_sound_diag *d) {
    unsigned i,ch;uint32_t hash=2166136261U;
    if(d->mode>=XF_SOUND_CASES)return 0;
    for(i=0;i<XF_SOUND_RATE;++i)for(ch=0;ch<2;++ch) {
        unsigned f=frequencies[d->mode][ch];
        int16_t sample=f?xf_sine_table[(i*(f/40))%1200]:0;
        uint16_t bits=(uint16_t)sample;unsigned at=i*4+ch*2;
        d->pcm[at]=(unsigned char)bits;d->pcm[at+1]=(unsigned char)(bits>>8);
    }
    /* Validate the actual packed bytes before ANY DMA submission. References
     * are independently generated by scripts/make_audio_sine.py. Host tests
     * additionally compare every sample with sin(2*pi*f*n/48000). */
    for(i=0;i<sizeof(d->pcm);++i)hash=(hash^d->pcm[i])*16777619U;
    d->pcm_hash=hash;d->verified=hash==expected_hash[d->mode];return d->verified;
}
int xf_sound_diag_start(xf_sound_diag *d,int busy,uint32_t now) {
    xf_audio_backend backend=d->backend;unsigned mode=d->mode,seconds=d->seconds;
    if(busy || xf_sound_diag_active(d)){snprintf(d->message,sizeof(d->message),"Audio owned by playback/tone. Stop it and wait for cleanup first.");return 0;}
    if(d->backend.queued(d->backend.context)) {error(d,"DMA is not empty (or invalid). No test submitted; stop playback or cold boot.");return 0;}
    xf_sound_diag_init(d,&backend);d->mode=mode;d->seconds=seconds;
    if((seconds!=1 && seconds!=60) || !xf_sound_diag_prepare(d)) {error(d,"PCM preflight failed; nothing submitted to DMA.");return 0;}
    d->target_frames=seconds*XF_SOUND_RATE;d->progress_at=(uint64_t)now*1000;d->state=XF_TONE_PLAYING;
    snprintf(d->message,sizeof(d->message),"PCM bytes verified; confirm actual clean pitch/channel output.");return 1;
}
void xf_sound_diag_stop(xf_sound_diag *d) {
    if(!xf_sound_diag_active(d))return;
    d->cancelled=1;d->state=XF_TONE_DRAINING;
    snprintf(d->message,sizeof(d->message),"Stopping: drain submitted PCM without hardware reinitialisation.");
}
void xf_sound_diag_tick_us(xf_sound_diag *d,uint64_t now) {
    unsigned budget,previous=d->queued,played;int q;
    if(!xf_sound_diag_active(d))return;
    if(d->last_tick && now-d->last_tick>d->max_service_gap_us)d->max_service_gap_us=now-d->last_tick;
    d->last_tick=now;q=d->backend.queued(d->backend.context);
    if(q<0 || q>65536 || (unsigned)q>d->submitted){error(d,"Invalid DMA queue reading; no further PCM submitted.");return;}
    d->queued=(unsigned)q;played=(d->submitted-d->queued)/4;
    if(played<d->played) {
        /* A backwards device count cannot be a valid rate measurement. Keep
         * the displayed position monotonic and restart the measurement window. */
        ++d->counter_faults;d->rate_at=d->rate_us=0;d->rate_frames=0;
    } else d->played=played;
    if(d->queued<previous)d->progress_at=now;
    if(d->played && !d->rate_at){d->rate_at=now;d->rate_begin=d->played;}
    if(d->rate_at && d->played-d->rate_begin>=XF_SOUND_RATE) {
        d->rate_us=now-d->rate_at;d->rate_frames=d->played-d->rate_begin;
        d->rate_at=now;d->rate_begin=d->played;
    }
    if(d->state==XF_TONE_DRAINING && !d->queued) {
        d->finished_at=now;d->state=XF_TONE_DONE;
        snprintf(d->message,sizeof(d->message),"DMA drained. Hardware pitch/quality is UNCONFIRMED until heard.");return;
    }
    if(d->submitted && now-d->progress_at>=2000000){error(d,"DMA made no progress for 2s; no reset/rewrite. Cold boot if stuck.");return;}
    if(d->submitted && !d->queued && d->state==XF_TONE_PLAYING)++d->underruns;
    for(budget=0;budget<4 && d->state==XF_TONE_PLAYING && d->queued+sizeof(d->block)<=XF_SOUND_QUEUE_BYTES;++budget) {
        unsigned frames=d->target_frames-d->frames,offset,first;
        if(d->backend.available(d->backend.context)<4096)return;
        if(frames>512)frames=512;
        offset=(d->frames%XF_SOUND_RATE)*4;first=sizeof(d->pcm)-offset;
        if(first>frames*4)first=frames*4;
        memset(d->block,0,sizeof(d->block));
        memcpy(d->block,d->pcm+offset,first);
        if(first<frames*4)memcpy(d->block+first,d->pcm,frames*4-first);
        if(!d->submitted){d->started_at=now;d->progress_at=now;}
        /* SDK copies synchronously into its own aligned 64KiB DMA ring before
         * returning. This scratch block is never directly owned by hardware. */
        d->backend.submit(d->backend.context,d->block,sizeof(d->block));
        d->frames+=frames;d->submitted+=sizeof(d->block);d->queued+=sizeof(d->block);
        if(d->frames==d->target_frames)d->state=XF_TONE_DRAINING;
    }
}
void xf_sound_diag_tick(xf_sound_diag *d,uint32_t now){xf_sound_diag_tick_us(d,(uint64_t)now*1000);}
