#!/usr/bin/env python3
"""Regenerate deterministic 48 kHz PCM sine table and independent FNV references."""
import math
from pathlib import Path
import struct
ROOT = Path(__file__).resolve().parents[1]
table = [math.floor(6000 * math.sin(2 * math.pi * i / 1200) + .5) for i in range(1200)]
lines = ['/* Generated by scripts/make_audio_sine.py; one quantised sine period. */',
         '#ifndef XF_SOUND_SINE_TABLE_H', '#define XF_SOUND_SINE_TABLE_H', '#include <stdint.h>',
         'static const int16_t xf_sine_table[1200] = {']
lines += ['    ' + ','.join(map(str, table[i:i+16])) + ',' for i in range(0, 1200, 16)]
lines += ['};', '#endif', '']
(ROOT / 'platform/xenon/sound_sine_table.h').write_text('\n'.join(lines))
for left, right in ((440,440),(880,880),(1000,1000),(0,0),(440,0),(0,440),(440,880)):
    fingerprint = 2166136261
    for i in range(48000):
        for hz in (left, right):
            sample = table[(i*(hz//40)) % 1200] if hz else 0
            for byte in struct.pack('<h', sample):
                fingerprint = ((fingerprint ^ byte) * 16777619) & 0xffffffff
    print(f'{left}/{right} Hz: 0x{fingerprint:08x}U')
